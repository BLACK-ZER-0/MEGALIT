@dataclass(frozen=True)
class Match:
    field: str
    pattern: str
    weight: int = 30
    # loose=True → fireeye-wave token: recall booster, capped at MEDIUM
    loose: bool = False


@dataclass
class Signature:
    vendor: str
    role: str
    matches: List[Match]


@dataclass
class Evidence:
    vendor: str
    role: str
    field: str
    pattern: str
    sample: str
    weight: int
    source: str = ""
    loose: bool = False


def S(vendor: str, role: str, raw: List[Tuple[str, str, int]]) -> Signature:
    return Signature(vendor, role, [Match(f, p, w) for (f, p, w) in raw])


