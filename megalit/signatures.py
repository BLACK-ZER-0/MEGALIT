# ═══════════ fireeye loose-token wave (detection-recall parity) ═════════════
#
# fireeye_v3 matches its tokens loosely anywhere in the headers / cookies /
# body — that is WHY it finds more vendors on the same target than a strictly
# anchored DB.  We import its full token set (megalit_tokens.TOKENS, generated
# from fireeye_v3.py's WAF_DB) and convert every token into a Megalit match so
# recall is identical.  Precision is kept by Megalit's curated anchored
# signatures plus the DEFINITIVE tier below.

# fireeye type → Megalit role ordering (WAF first, like "WAF/CDN")
_FE_ROLE_ORDER = {"WAF": 0, "CDN": 1, "LB": 2, "CLOUD": 3, "PROXY": 4, "TECH": 5}


def _fe_role(raw: str) -> str:
    parts = [p.strip().upper() for p in str(raw or "WAF").split("/") if p.strip()]
    parts = [p for p in parts if p in _FE_ROLE_ORDER]
    if not parts:
        parts = ["WAF"]
    return "/".join(sorted(set(parts), key=lambda p: _FE_ROLE_ORDER[p]))


def _fe_signatures() -> "List[Signature]":
    from .megalit_tokens import TOKENS
    sigs = []
    for vendor, tok in TOKENS.items():
        ms = []
        for t in tok.get("headers", []):
            ms.append(Match("header", t, 30, loose=True))
        for t in tok.get("cookies", []):
            ms.append(Match("cookie", t, 35, loose=True))
        for t in tok.get("body", []):
            ms.append(Match("body", t, 40, loose=True))
        for t in tok.get("server", []):
            ms.append(Match("header_value", t, 25, loose=True))
            ms.append(Match("header_name", t, 25, loose=True))
        if ms:
            sigs.append(Signature(vendor, _fe_role(tok.get("type", "WAF")), ms))
    return sigs


